export type Emoji = (typeof EMOJIS_BY_RARITY)[Rarity][number];

const rarityByEmoji = new Map<string, Rarity>(
  RARITIES.flatMap(({ id }) => EMOJIS_BY_RARITY[id].map((emoji) => [emoji, id] as const)),
);

export const isEmoji = (value: unknown): value is Emoji =>
  typeof value === "string" && rarityByEmoji.has(value);

export const getRarity = (emoji: Emoji): Rarity => rarityByEmoji.get(emoji) ?? "common";
