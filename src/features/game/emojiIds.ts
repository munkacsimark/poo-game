export type EmojiId = (typeof EMOJI_IDS)[Emoji];

/** Old id → current id, for emojis that were renamed or replaced. Empty so far. */
const EMOJI_ID_ALIASES: Readonly<Record<string, EmojiId>> = {};

const emojiById = new Map<string, Emoji>(
  RARITIES.flatMap(({ id }) => EMOJIS_BY_RARITY[id]).map((emoji) => [EMOJI_IDS[emoji], emoji]),
);

export const emojiId = (emoji: Emoji): EmojiId => EMOJI_IDS[emoji];

/** The emoji for a stored id (following aliases), or undefined for ids this version doesn't know. */
export const emojiFromId = (id: string): Emoji | undefined =>
  emojiById.get(EMOJI_ID_ALIASES[id] ?? id);
